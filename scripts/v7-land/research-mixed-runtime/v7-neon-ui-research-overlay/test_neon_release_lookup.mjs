import assert from 'node:assert/strict';
import {createNeonReleaseLookup} from './neon-release-lookup.mjs';
let seen;
const lookup=createNeonReleaseLookup(async(sql,args)=>{seen={sql,args};return {rows:[{release_id:args[0]}]}});
assert.equal((await lookup('fictional')).release_id,'fictional');
assert.match(seen.sql,/release_id=\$1/);assert.match(seen.sql,/octet_length\(manifest::text\)/);assert.match(seen.sql,/octet_length\(records::text\)/);assert.deepEqual(seen.args,['fictional']);
await assert.rejects(()=>lookup(''),/invalid/);await assert.rejects(()=>lookup('x'.repeat(513)),/invalid/);
await assert.rejects(()=>createNeonReleaseLookup(async()=>({rows:[]}))('fictional'),/not found/);
await assert.rejects(()=>createNeonReleaseLookup(async()=>({rows:[{},{}]}))('fictional'),/not found/);
assert.throws(()=>createNeonReleaseLookup(null));
console.log('Neon release lookup synthetic tests passed');
