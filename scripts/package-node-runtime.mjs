const UNUSED_KIND='node-gyp-unused-postinstall-regeneration-state-v1';
const CONFIG_PREFIX='# Do not edit. File was generated by node-gyp\'s "configure" step\n';
// Optional metadata recognition gets a bounded buffer. Larger metadata is still
// streamed and fully inventoried, and receives no normalization. No runtime
// member, binary, or dependency is rejected or omitted because of its size.
const METADATA_BUFFER=1024*1024;

function ordinary(root,relative){
  need(typeof relative==='string'&&relative.length>0&&!path.isAbsolute(relative)&&
    relative.split('/').every(part=>part&&part!=='.'&&part!=='..'),'Safe installed member path required');
  let file=root;
  for(const part of relative.split('/')){file=path.join(file,part);need(!fs.lstatSync(file).isSymbolicLink(),'Ordinary installed provenance path required');}
  need(fs.lstatSync(file).isFile(),'Ordinary installed provenance member required');return file;
}
function digestFile(file,{capture=false}={}){
  const namedBefore=fs.lstatSync(file);
  need(namedBefore.isFile()&&!namedBefore.isSymbolicLink(),'Ordinary installed dependency required');
  const fd=fs.openSync(file,fs.constants.O_RDONLY|fs.constants.O_NOFOLLOW);
  try{
    const before=fs.fstatSync(fd);need(before.isFile(),'Ordinary installed dependency required');
    const digest=createHash('sha256'),buffer=Buffer.alloc(1024*1024),chunks=[];let bytes=0;
    while(true){const count=fs.readSync(fd,buffer,0,buffer.length,null);if(!count)break;bytes+=count;
      need(Number.isSafeInteger(bytes),'Installed member exceeds exact numeric byte accounting');digest.update(buffer.subarray(0,count));
      if(capture&&before.size<=METADATA_BUFFER)chunks.push(Buffer.from(buffer.subarray(0,count)));
    }
    const after=fs.fstatSync(fd),namedAfter=fs.lstatSync(file);
    need(bytes===before.size&&namedAfter.isFile()&&!namedAfter.isSymbolicLink()&&
      ['dev','ino','size','mode','mtimeMs','ctimeMs'].every(key=>namedBefore[key]===before[key]&&
        before[key]===after[key]&&after[key]===namedAfter[key]),'Installed member changed during observation');
    return {bytes,sha256:digest.digest('hex'),mode:before.mode&0o111?'100755':'100644',
      ...(capture&&before.size<=METADATA_BUFFER?{body:Buffer.concat(chunks)}:{})};
  }finally{fs.closeSync(fd);}
}
function metadata(root,relative){
  const file=ordinary(root,relative),value=digestFile(file,{capture:true});
  if(!value.body||value.mode!=='100644')return null;return {path:relative,...value};
}
function generatorProvenance(nodeExecutable){
  const root=path.resolve(path.dirname(nodeExecutable),'../lib/node_modules/npm/node_modules/node-gyp');
  try{
    const manifest=metadata(root,'package.json');if(!manifest)return null;
    const pkg=JSON.parse(manifest.body);
    if(pkg.name!=='node-gyp'||!Object.hasOwn(GENERATOR_VERSIONS,pkg.version))return null;
    const files=[],expectedFiles={...GENERATOR_FILES,'gyp/pylib/gyp/__init__.py':GENERATOR_VERSIONS[pkg.version]};
    for(const [name,expected]of Object.entries(expectedFiles)){
      const value=digestFile(ordinary(root,name));if(value.sha256!==expected)return null;
      files.push({path:name,bytes:value.bytes,sha256:value.sha256});
    }
    return {root,entry:path.join(root,'gyp/gyp_main.py'),version:pkg.version,files};
  }catch{return null;}
}
// The generator's POSIX encoder emits these safe unescaped tokens. Shell
// substitutions, escapes, arbitrary command tails and unfamiliar syntax cannot
// be metadata-equivalent. Their complete raw bytes remain the identity.
function commandTokens(command){
  const tokens=[];let at=0;
  while(at<command.length){
    const start=at,quoted=command[at]==='"';if(quoted)at++;
    const valueStart=at;
    while(at<command.length&&(quoted?/[A-Za-z0-9_./=,:+@<()-]/:/[A-Za-z0-9_./=,:+@-]/).test(command[at]))at++;
    if(at===valueStart)return null;
    const value=command.slice(valueStart,at);
    if(quoted){if(command[at]!== '"')return null;at++;}
    tokens.push({value,quoted,start,end:at,valueStart,valueEnd:valueStart+value.length});
    if(at===command.length)break;
    if(command[at++]!==' '||command[at]===' ')return null;
  }
  return tokens;
}
function normalizedRegeneration(root,relative,raw,lock,generator,unusedFamily=false){
  if(!generator||raw.mode!=='100644'||!raw.body)return null;
  // Match a package's root build Makefile, never all files beneath build/ and
  // never a basename elsewhere. Nested/scoped npm packages remain supported.
  if(!relative.endsWith('/build/Makefile'))return null;
  const packagePath=relative.slice(0,-'/build/Makefile'.length);
  if(!/(?:^|\/)node_modules\/(?:@[^/]+\/)?[^/]+$/.test(packagePath))return null;
  try{
    const record=lock?.packages?.[packagePath];
    if(unusedFamily){
      if(typeof record?.version!=='string'||typeof record.integrity!=='string'||!/^sha(?:256|384|512)-[A-Za-z0-9+/]+={0,2}$/.test(record.integrity))return null;
    }else if(record?.hasInstallScript!==true)return null;
    const manifest=metadata(root,packagePath+'/package.json'),binding=metadata(root,packagePath+'/binding.gyp');
    const wrapper=metadata(root,packagePath+'/build/binding.Makefile');
    if(!manifest||!binding||!wrapper||!wrapper.body.toString('utf8').startsWith(GENERATED))return null;
    const pkg=JSON.parse(manifest.body);
    if(typeof pkg.name!=='string'||pkg.version!==record.version||!unusedFamily&&pkg.gypfile===false)return null;
    const text=raw.body.toString('utf8');if(!Buffer.from(text).equals(raw.body)||text.includes('\0')||text.includes('\r'))return null;
    if(!text.startsWith(PREAMBLE)||!text.endsWith(FOOTER)||
      !text.includes('\nMAKEFLAGS=-r\n')||!text.includes('\nsrcdir := ..\nabs_srcdir := $(abspath $(srcdir))\n'))return null;
    const marker='quiet_cmd_regen_makefile = ACTION Regenerating $@\ncmd_regen_makefile = cd $(srcdir); ';
    const start=text.indexOf(marker);
    if(start<0||text.indexOf(marker,start+marker.length)!==-1||
      (text.match(/\bregen_makefile\b/g)??[]).length!==1||
      (text.match(/\bcmd_regen_makefile\b/g)??[]).length!==1||
      (text.match(/\bquiet_cmd_regen_makefile\b/g)??[]).length!==1)return null;
    const commandStart=start+marker.length,end=text.indexOf('\n',commandStart);
    if(end<0)return null;
    const command=text.slice(commandStart,end),tokens=commandTokens(command);
    if(!tokens||tokens.length<7||tokens[0].value!==generator.entry||tokens[1].value!=='-fmake'||
      tokens[2].value!=='--ignore-environment'||tokens.at(-1).value!=='binding.gyp')return null;
    const flags=tokens.slice(3,-1);
    if(flags.some(token=>!/^-(?:D[A-Za-z_][A-Za-z0-9_]*=[A-Za-z0-9_./=,:+@-]+|I[A-Za-z0-9_./=,:+@-]+|G[A-Za-z_][A-Za-z0-9_]*=[A-Za-z0-9_./=,:+@-]+|-depth=\.|-generator-output=build|-toplevel-dir=\.|-no-parallel)$/.test(token.value)&&
      !(token.quoted&&/^-Dnode_lib_file=\/[A-Za-z0-9_./-]+\/<\(target_arch\)\/[A-Za-z0-9_.-]+\.lib$/.test(token.value))))return null;
    for(const required of ['--depth=.','--generator-output=build','--toplevel-dir=.'])
      if(flags.filter(token=>token.value===required).length!==1)return null;
    const fields=flags.filter(token=>token.value.startsWith('-Dmodule_root_dir='));if(fields.length!==1)return null;
    const field=fields[0],physicalRoot=path.join(root,packagePath);
    if(field.value!=='-Dmodule_root_dir='+physicalRoot)return null;
    const following=text.slice(end+1);
    if(!/^Makefile: [^\n]*\$\(srcdir\)\/binding\.gyp[^\n]*\n\t\$\(call do_cmd,regen_makefile\)\n\n/.test(following))return null;
    if(unusedFamily){
      if(generator.version!=='12.4.0'||flags.filter(token=>token.value==='-I'+physicalRoot+'/build/config.gypi').length!==1)return null;
      const configuration=metadata(root,packagePath+'/build/config.gypi');if(!configuration)return null;
      const configText=configuration.body.toString('utf8');
      if(!Buffer.from(configText).equals(configuration.body)||!configText.startsWith(CONFIG_PREFIX))return null;
      const config=JSON.parse(configText.slice(CONFIG_PREFIX.length));
      if(!exactKeys(config,['variables','target_defaults'])||!config.variables||typeof config.variables!=='object'||Array.isArray(config.variables)||
        !config.target_defaults||typeof config.target_defaults!=='object'||Array.isArray(config.target_defaults)||
        CONFIG_PREFIX+JSON.stringify(config,null,2)+'\n'!==configText||
        typeof config.variables.nodedir!=='string'||!path.isAbsolute(config.variables.nodedir)||
        typeof config.variables.python!=='string'||!path.isAbsolute(config.variables.python)||
        Object.hasOwn(config.variables,'local_prefix')&&config.variables.local_prefix!==root)return null;
      const files=[...generator.files];
      for(const [name,expected]of Object.entries(CONFIG_GENERATOR_FILES)){
        const value=digestFile(ordinary(generator.root,name));if(value.sha256!==expected)return null;
        files.push({path:name,bytes:value.bytes,sha256:value.sha256});
      }
      const pin=value=>({path:value.path,bytes:value.bytes,sha256:value.sha256});
      return {kind:UNUSED_KIND,package_path:packagePath,generator:{version:generator.version,files},
        package_manifest:pin(manifest),binding:pin(binding),generated_wrapper:pin(wrapper),
        makefile:{path:relative,bytes:raw.bytes,sha256:raw.sha256},configuration:pin(configuration)};
    }
    const offset=commandStart+field.valueStart+'-Dmodule_root_dir='.length;
    const normalized=text.slice(0,offset)+'@worldatlas-package-root@'+text.slice(offset+physicalRoot.length);
    const body=Buffer.from(normalized);
    return {effective:{bytes:body.length,sha256:hash(body)},normalization:{
      kind:'node-gyp-make-regeneration-module-root-v1',field:'cmd_regen_makefile/-Dmodule_root_dir',
      physical_root:physicalRoot,package_path:packagePath,generator:{version:generator.version,files:generator.files},
      package_manifest:{path:manifest.path,bytes:manifest.bytes,sha256:manifest.sha256},
      binding:{path:binding.path,bytes:binding.bytes,sha256:binding.sha256},
      generated_wrapper:{path:wrapper.path,bytes:wrapper.bytes,sha256:wrapper.sha256}}};
  }catch{return null;}
}

export function effectiveNodeDependencyInventory(identity){
  return identity.dependencies.inventory.filter(row=>!row.exclusion).map(row=>Object.hasOwn(row,'link')?{path:row.path,link:row.link}:
    {path:row.path,bytes:row.effective?.bytes??row.bytes,sha256:row.effective?.sha256??row.sha256,mode:row.mode});
}

const exactKeys=(value,keys)=>value&&typeof value==='object'&&!Array.isArray(value)&&
  Object.keys(value).sort().join(',')===[...keys].sort().join(',');
const digest=value=>typeof value==='string'&&/^[a-f0-9]{64}$/.test(value);
const size=value=>Number.isSafeInteger(value)&&value>=0;
const memberPath=value=>typeof value==='string'&&value.startsWith('node_modules/')&&!value.includes('\\')&&!value.includes('\0')&&
  value.split('/').every(part=>part&&part!=='.'&&part!=='..');
function descriptorMatches(pin,row){
  return exactKeys(pin,['path','bytes','sha256'])&&row&&row.mode==='100644'&&!row.normalization&&!row.exclusion&&
    pin.path===row.path&&pin.bytes===row.bytes&&pin.sha256===row.sha256;
}
export function validateNodeIdentity(identity){
  need(exactKeys(identity,['node','dependencies']),'Complete versioned Node identity required');
  need(exactKeys(identity.node,['bytes','sha256'])&&size(identity.node.bytes)&&identity.node.bytes>0&&digest(identity.node.sha256),
    'Exact Node executable identity required');
  const dep=identity.dependencies;
  need(exactKeys(dep,['files','bytes','sha256','raw_bytes','raw_sha256','inventory'])&&Array.isArray(dep.inventory)&&
    Number.isSafeInteger(dep.files)&&dep.files>=0&&size(dep.bytes)&&size(dep.raw_bytes)&&digest(dep.sha256)&&digest(dep.raw_sha256),
    'Complete raw/effective dependency roster required');
  const rows=new Map();let previous='';
  for(const row of dep.inventory){
    need(row&&memberPath(row.path)&&!rows.has(row.path)&&(!previous||previous<row.path),'Sorted unique ordinary dependency paths required');
    previous=row.path;rows.set(row.path,row);
    if(Object.hasOwn(row,'link')){
      need(exactKeys(row,['path','link'])&&typeof row.link==='string'&&row.link.length>0&&!row.link.includes('\0'),
        'Exact installed link evidence required');
    }else{
      const normalized=Object.hasOwn(row,'normalization'),excluded=Object.hasOwn(row,'exclusion');
      need(exactKeys(row,excluded?['path','bytes','sha256','mode','exclusion']:normalized?['path','bytes','sha256','mode','effective','normalization']:['path','bytes','sha256','mode'])&&
        size(row.bytes)&&digest(row.sha256)&&['100644','100755'].includes(row.mode),'Complete raw dependency descriptor required');
      if(excluded)need(row.mode==='100644','Only ordinary generated document roles can be excluded');
      if(normalized)need(row.mode==='100644'&&exactKeys(row.effective,['bytes','sha256'])&&size(row.effective.bytes)&&digest(row.effective.sha256)&&
        row.effective.sha256!==row.sha256,'Ordinary generated metadata effective descriptor required');
    }
  }
  for(const row of rows.values()){
    const parts=row.path.split('/');
    for(let at=2;at<parts.length;at++)need(!rows.has(parts.slice(0,at).join('/')),'Dependency file/link cannot parent another member');
    if(Object.hasOwn(row,'link')&&!path.posix.isAbsolute(row.link)){
      const target=path.posix.normalize(path.posix.join(path.posix.dirname(row.path),row.link));
      need(memberPath(target)&&target!==row.path&&
        (rows.has(target)||dep.inventory.some(item=>item.path.startsWith(target+'/'))),
        'Installed relative link must target the retained installation roster');
    }
    if(row.exclusion){
      const value=row.exclusion;
      need(exactKeys(value,['kind','role','package_path','generator','package_manifest','binding','generated_wrapper','makefile','configuration'])&&
        value.kind===UNUSED_KIND&&['makefile','configuration'].includes(value.role)&&memberPath(value.package_path)&&
        /(?:^|\/)node_modules\/(?:@[^/]+\/)?[^/]+$/.test(value.package_path)&&
        row.path===value.package_path+(value.role==='makefile'?'/build/Makefile':'/build/config.gypi'),
        'Known unused post-install regeneration document role required');
      const generator=value.generator,expected={...GENERATOR_FILES,'gyp/pylib/gyp/__init__.py':GENERATOR_VERSIONS['12.4.0'],...CONFIG_GENERATOR_FILES};
      need(exactKeys(generator,['version','files'])&&generator.version==='12.4.0'&&Array.isArray(generator.files)&&
        generator.files.length===Object.keys(expected).length,'Complete reviewed configure generator evidence required');
      const observed=new Set();
      for(const file of generator.files){
        need(exactKeys(file,['path','bytes','sha256'])&&Object.hasOwn(expected,file.path)&&!observed.has(file.path)&&
          size(file.bytes)&&file.bytes>0&&file.sha256===expected[file.path],'Exact reviewed configure source identity required');observed.add(file.path);
      }
      for(const [role,suffix]of [['package_manifest','/package.json'],['binding','/binding.gyp'],['generated_wrapper','/build/binding.Makefile']])
        need(value[role]?.path===value.package_path+suffix&&descriptorMatches(value[role],rows.get(value[role].path)),
          'Unused document provenance must bind actual raw package members');
      for(const [role,suffix]of [['makefile','/build/Makefile'],['configuration','/build/config.gypi']]){
        const pin=value[role],member=rows.get(value.package_path+suffix);
        need(exactKeys(pin,['path','bytes','sha256'])&&member&&member.mode==='100644'&&pin.path===member.path&&
          pin.bytes===member.bytes&&pin.sha256===member.sha256&&member.exclusion?.role===role&&
          JSON.stringify({...member.exclusion,role:undefined})===JSON.stringify({...value,role:undefined}),
          'Complete paired raw regeneration document evidence required');
      }
    }
    if(!row.normalization)continue;
    const value=row.normalization;
    need(exactKeys(value,['kind','field','physical_root','package_path','generator','package_manifest','binding','generated_wrapper'])&&
      value.kind==='node-gyp-make-regeneration-module-root-v1'&&value.field==='cmd_regen_makefile/-Dmodule_root_dir'&&
      memberPath(value.package_path)&&/(?:^|\/)node_modules\/(?:@[^/]+\/)?[^/]+$/.test(value.package_path)&&
      row.path===value.package_path+'/build/Makefile','Known regeneration normalization declaration required');
    need(typeof value.physical_root==='string'&&/^\/[A-Za-z0-9_./=,:+@-]+$/.test(value.physical_root)&&
      path.posix.normalize(value.physical_root)===value.physical_root&&value.physical_root.endsWith('/'+value.package_path)&&
      row.effective.bytes===row.bytes-Buffer.byteLength(value.physical_root)+Buffer.byteLength('@worldatlas-package-root@'),
      'Exactly one physical package-root field must explain effective byte count');
    const generator=value.generator;
    need(exactKeys(generator,['version','files'])&&Object.hasOwn(GENERATOR_VERSIONS,generator.version)&&Array.isArray(generator.files),
      'Reviewed generator provenance required');
    const expected={...GENERATOR_FILES,'gyp/pylib/gyp/__init__.py':GENERATOR_VERSIONS[generator.version]},observed=new Set();
    for(const file of generator.files){
      need(exactKeys(file,['path','bytes','sha256'])&&Object.hasOwn(expected,file.path)&&!observed.has(file.path)&&
        size(file.bytes)&&file.bytes>0&&file.sha256===expected[file.path],'Exact reviewed generator source identity required');observed.add(file.path);
    }
    need(observed.size===Object.keys(expected).length,'Complete reviewed generator source evidence required');
    for(const [role,suffix]of [['package_manifest','/package.json'],['binding','/binding.gyp'],['generated_wrapper','/build/binding.Makefile']])
      need(value[role]?.path===value.package_path+suffix&&descriptorMatches(value[role],rows.get(value[role].path)),
        'Normalization provenance must bind actual raw inventory members');
  }
  const raw=dep.inventory.map(({effective,normalization,exclusion,...row})=>row),effective=effectiveNodeDependencyInventory(identity);
  const total=list=>list.reduce((sum,row)=>sum+(row.bytes??0),0);
  need(dep.files===dep.inventory.length&&dep.raw_bytes===total(raw)&&dep.bytes===total(effective)&&
    dep.raw_sha256===hash(JSON.stringify(raw))&&dep.sha256===hash(JSON.stringify(effective)),
    'Node inventory summaries differ from complete raw/effective rows');
  return identity;
}

export function installedNodeIdentity(root){
  root=fs.realpathSync(root);
  const installation=path.join(root,'node_modules');
  need(fs.lstatSync(installation).isDirectory()&&!fs.lstatSync(installation).isSymbolicLink(),'Ordinary node_modules root required');
  const nodeExecutable=fs.realpathSync(process.execPath),runtime=digestFile(nodeExecutable);
  const generator=generatorProvenance(nodeExecutable);
  let lock=null;
  try{const value=metadata(root,'package-lock.json');if(value)lock=JSON.parse(value.body);}catch{}
  const inventory=[],unusedFamilies=new Map();
  // These two documents are unused only in the audited post-install package
  // producer programme. Reuse still requires its complete exact programme gate;
  // this is not a claim that node-gyp's build recipes are universally inert.
  const unusedDocument=relative=>{
    const match=/^(.*)\/build\/(Makefile|config\.gypi)$/.exec(relative);if(!match)return null;
    const packagePath=match[1];
    if(!unusedFamilies.has(packagePath)){
      let family=null;
      try{const makefile=metadata(root,packagePath+'/build/Makefile');
        if(makefile)family=normalizedRegeneration(root,makefile.path,makefile,lock,generator,true);
      }catch{}
      unusedFamilies.set(packagePath,family);
    }
    const family=unusedFamilies.get(packagePath);
    return family?{...family,role:match[2]==='Makefile'?'makefile':'configuration'}:null;
  };
  const visit=relative=>{
    const file=path.join(root,relative),stat=fs.lstatSync(file);
    if(stat.isSymbolicLink()){
      const target=fs.realpathSync(file);need(target.startsWith(installation+path.sep),'Installed dependency link escapes installation');
      inventory.push({path:relative,link:fs.readlinkSync(file)});
    }else if(stat.isDirectory()){
      for(const name of fs.readdirSync(file).sort())visit(relative+'/'+name);
    }else{
      need(stat.isFile(),'Ordinary installed dependency required');
      const value=digestFile(file,{capture:relative.endsWith('/build/Makefile')});
      const raw={path:relative,bytes:value.bytes,sha256:value.sha256,mode:value.mode};
      const exclusion=unusedDocument(relative);
      const normalized=exclusion?null:normalizedRegeneration(root,relative,value,lock,generator);
      inventory.push({...raw,...normalized,...(exclusion?{exclusion}:{})});
    }
  };
  visit('node_modules');
  inventory.sort((a,b)=>a.path<b.path?-1:a.path>b.path?1:0);
  const identity={node:{bytes:runtime.bytes,sha256:runtime.sha256},dependencies:{inventory}};
  const effective=effectiveNodeDependencyInventory(identity);
  const rawRows=inventory.map(({effective,normalization,exclusion,...raw})=>raw);
  const total=rows=>{const bytes=rows.reduce((sum,row)=>sum+(row.bytes??0),0);need(Number.isSafeInteger(bytes),'Installed inventory exceeds exact numeric byte accounting');return bytes;};
  identity.dependencies={files:inventory.length,bytes:total(effective),sha256:hash(JSON.stringify(effective)),
    raw_bytes:total(rawRows),raw_sha256:hash(JSON.stringify(rawRows)),inventory};
  return validateNodeIdentity(identity);
}
