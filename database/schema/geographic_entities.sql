-- Geographic hierarchy and stable entity/physical-class map codes.
CREATE TABLE atlas.geographic_levels (
    id text PRIMARY KEY CHECK (atlas.nonblank(id)),
    parent_id text REFERENCES atlas.geographic_levels(id) DEFERRABLE INITIALLY DEFERRED
);
CREATE UNIQUE INDEX geographic_level_root ON atlas.geographic_levels ((true)) WHERE parent_id IS NULL;

CREATE TABLE atlas.geographic_entities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 0 AND 4294967295),
    name text NOT NULL CHECK (atlas.nonblank(name)),
    level_id text NOT NULL REFERENCES atlas.geographic_levels(id),
    parent_id bigint REFERENCES atlas.geographic_entities(id) DEFERRABLE INITIALLY DEFERRED,
    physical_class text NOT NULL CHECK (physical_class IN ('land','water','mixed')),
    color_rgb text CHECK (color_rgb ~ '^#[0-9A-Fa-f]{6}$'),
    CHECK (id <> parent_id),
    CONSTRAINT geographic_entity_root_id CHECK ((id=0) = (parent_id IS NULL))
);
COMMENT ON COLUMN atlas.geographic_entities.color_rgb IS 'Latest generated RGB from a completed map build.';

CREATE TABLE atlas.map_category_bindings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 4294967295),
    entity_id bigint NOT NULL REFERENCES atlas.geographic_entities(id) ON DELETE CASCADE,
    physical_class text NOT NULL CHECK (physical_class IN ('land','water')),
    UNIQUE (entity_id, physical_class)
);

CREATE FUNCTION atlas.sync_map_category_bindings() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM atlas.map_category_bindings
  WHERE entity_id=NEW.id AND NEW.physical_class NOT IN (physical_class, 'mixed');

  INSERT INTO atlas.map_category_bindings (entity_id, physical_class)
  SELECT NEW.id, kind
  FROM (VALUES ('land'), ('water')) AS classes(kind)
  WHERE NEW.physical_class IN (kind, 'mixed')
    AND NOT EXISTS (
      SELECT FROM atlas.map_category_bindings WHERE entity_id=NEW.id AND physical_class=kind
    )
  ORDER BY kind;
  RETURN NULL;
END $$;

CREATE TRIGGER map_category_bindings_sync AFTER INSERT OR UPDATE OF physical_class
ON atlas.geographic_entities FOR EACH ROW WHEN (NEW.parent_id IS NOT NULL)
EXECUTE FUNCTION atlas.sync_map_category_bindings();

CREATE FUNCTION atlas.validate_geographic_entity(ident bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE e atlas.geographic_entities%ROWTYPE; p atlas.geographic_entities%ROWTYPE;
        expected_level text;
BEGIN
  SELECT * INTO e FROM atlas.geographic_entities WHERE id=ident FOR SHARE;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT parent_id INTO expected_level FROM atlas.geographic_levels WHERE id=e.level_id FOR SHARE;
  IF e.parent_id IS NULL THEN
    IF expected_level IS NOT NULL THEN RAISE EXCEPTION 'root entity has a non-root level'; END IF;
  ELSE
    SELECT * INTO p FROM atlas.geographic_entities WHERE id=e.parent_id FOR SHARE;
    IF NOT FOUND OR p.level_id IS DISTINCT FROM expected_level
       OR (p.physical_class<>'mixed' AND p.physical_class<>e.physical_class) THEN
      RAISE EXCEPTION 'invalid parent for entity %', e.id;
    END IF;
  END IF;
  -- A child's validation locks its parent above, so the parent can read its children.
  IF EXISTS (
    SELECT FROM atlas.geographic_entities child JOIN atlas.geographic_levels l ON l.id=child.level_id
    WHERE child.parent_id=e.id AND (l.parent_id IS DISTINCT FROM e.level_id
      OR (e.physical_class<>'mixed' AND e.physical_class<>child.physical_class))
  ) THEN RAISE EXCEPTION 'entity % would invalidate its children', e.id; END IF;
  IF (SELECT array_agg(physical_class ORDER BY physical_class)
      FROM atlas.map_category_bindings WHERE entity_id=e.id)
     IS DISTINCT FROM (CASE
       WHEN e.parent_id IS NULL THEN NULL
       WHEN e.physical_class='mixed' THEN ARRAY['land','water']
       ELSE ARRAY[e.physical_class]
     END)
  THEN RAISE EXCEPTION 'map bindings do not match entity %', e.id; END IF;
END $$;

CREATE FUNCTION atlas.check_geographic_hierarchy() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ident bigint;
BEGIN
  IF TG_TABLE_NAME='geographic_levels' THEN
    IF EXISTS (
      WITH RECURSIVE ancestors AS (
        SELECT id,parent_id,ARRAY[id] AS path,false AS cycle FROM atlas.geographic_levels
        UNION ALL
        SELECT a.id,p.parent_id,a.path||p.id,p.id=ANY(a.path)
        FROM ancestors a JOIN atlas.geographic_levels p ON p.id=a.parent_id WHERE NOT a.cycle
      ) SELECT FROM ancestors WHERE cycle
    ) THEN RAISE EXCEPTION 'geographic levels contain a cycle'; END IF;
    FOR ident IN SELECT id FROM atlas.geographic_entities ORDER BY id LOOP
      PERFORM atlas.validate_geographic_entity(ident);
    END LOOP;
  ELSIF TG_TABLE_NAME='map_category_bindings' THEN
    IF TG_OP<>'DELETE' THEN
      PERFORM atlas.validate_geographic_entity(NEW.entity_id);
    END IF;
    IF TG_OP<>'INSERT' AND OLD.entity_id IS DISTINCT FROM NEW.entity_id THEN
      PERFORM atlas.validate_geographic_entity(OLD.entity_id);
    END IF;
  ELSE
    PERFORM atlas.validate_geographic_entity(NEW.id);
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER geographic_level_check AFTER INSERT OR UPDATE OR DELETE
ON atlas.geographic_levels DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION atlas.check_geographic_hierarchy();
CREATE CONSTRAINT TRIGGER geographic_entity_check AFTER INSERT OR UPDATE OF id,level_id,parent_id,physical_class
ON atlas.geographic_entities DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION atlas.check_geographic_hierarchy();
CREATE CONSTRAINT TRIGGER map_binding_check AFTER INSERT OR UPDATE OF entity_id,physical_class OR DELETE
ON atlas.map_category_bindings DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION atlas.check_geographic_hierarchy();
