-- Initial WorldAtlas schema for an empty database.
-- Load source records, decisions, and releases separately.
BEGIN;

-- Entity registry and grid codes

-- Registry identity is independent of display colors and review-grid codes.
-- This migration defines storage only; it does not publish or approve geography.
CREATE SCHEMA IF NOT EXISTS atlas;

CREATE TABLE atlas.geographic_entity_ids (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 4294967295),
    color_rgb text CHECK (color_rgb ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE atlas.entity_registry_revisions (
    revision text PRIMARY KEY CHECK (length(trim(revision)) > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE atlas.geographic_entities (
    revision text NOT NULL REFERENCES atlas.entity_registry_revisions(revision),
    id bigint NOT NULL REFERENCES atlas.geographic_entity_ids(id),
    name text NOT NULL CHECK (length(trim(name)) > 0),
    level text NOT NULL CHECK (level IN ('continent','subcontinent','region','area','province','location')),
    parent_id bigint,
    physical_class text CHECK (physical_class IN ('land','water')),
    PRIMARY KEY (revision, id),
    FOREIGN KEY (revision, parent_id) REFERENCES atlas.geographic_entities(revision, id)
      DEFERRABLE INITIALLY DEFERRED,
    CHECK ((level = 'continent') = (parent_id IS NULL)),
    CHECK ((level = 'location') = (physical_class IS NOT NULL)),
    CHECK (id <> parent_id)
);

-- Levels must be adjacent, so cycles are impossible. Deferred validation allows
-- an entire hierarchy to be inserted in any order within one transaction.
CREATE FUNCTION atlas.check_geographic_entity_parent() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE parent_level text;
BEGIN
  IF NEW.parent_id IS NOT NULL THEN
    SELECT level INTO parent_level FROM atlas.geographic_entities
      WHERE revision = NEW.revision AND id = NEW.parent_id;
    IF parent_level IS DISTINCT FROM (CASE NEW.level
      WHEN 'subcontinent' THEN 'continent' WHEN 'region' THEN 'subcontinent'
      WHEN 'area' THEN 'region' WHEN 'province' THEN 'area'
      WHEN 'location' THEN 'province' END) THEN
      RAISE EXCEPTION 'invalid parent level for entity %', NEW.id;
    END IF;
  END IF;
  -- A parent's level change must not invalidate existing children.
  IF EXISTS (SELECT 1 FROM atlas.geographic_entities c
    WHERE c.revision = NEW.revision AND c.parent_id = NEW.id
      AND NEW.level IS DISTINCT FROM (CASE c.level
        WHEN 'subcontinent' THEN 'continent' WHEN 'region' THEN 'subcontinent'
        WHEN 'area' THEN 'region' WHEN 'province' THEN 'area'
        WHEN 'location' THEN 'province' END)) THEN
    RAISE EXCEPTION 'invalid child level for entity %', NEW.id;
  END IF;
  RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER geographic_entity_parent_check
  AFTER INSERT OR UPDATE ON atlas.geographic_entities
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION atlas.check_geographic_entity_parent();

-- Review category codes and land/water styling are not geographic identities.
CREATE TABLE atlas.review_category_bindings (
    revision text NOT NULL,
    code integer NOT NULL CHECK (code > 0),
    entity_id bigint NOT NULL,
    physical_class text NOT NULL CHECK (physical_class IN ('land','water')),
    PRIMARY KEY (revision, code),
    FOREIGN KEY (revision, entity_id) REFERENCES atlas.geographic_entities(revision, id)
